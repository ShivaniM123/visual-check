/**
 * Hand-off texts: the AEM Coder / Workspace chat prompt (the PR's prompt.js) and a Markdown report.
 */
import { buildFixPrompt } from './prompt.js';

/** Stable key for an issue across re-runs (ids are renumbered every run). */
export const issueKey = (i) => [i.width, i.category, i.property || '', i.m?.selector || i.o?.selector || '', i.title.replace(/\d+(\.\d+)?/g, '#')].join('|');

export function statusesById(report, statuses) {
  const out = {};
  report.results.flatMap((r) => r.issues).forEach((i) => {
    if (statuses[issueKey(i)]) out[i.id] = statuses[issueKey(i)];
  });
  return out;
}

export function coderPrompt(report, statuses) {
  return buildFixPrompt(report, statusesById(report, statuses));
}

const SEV = { high: 'High', medium: 'Medium', low: 'Low' };
const cell = (v) => String(v ?? '–').replace(/\|/g, '\\|').replace(/\s+/g, ' ');

export function markdownReport(report, statuses) {
  const byId = statusesById(report, statuses);
  const out = [
    `# Parity report: ${report.migrated}`,
    '',
    `- Original page: ${report.original}`,
    `- Migrated page: ${report.migrated}`,
    `- Checked: ${new Date(report.created).toLocaleString()} · widths ${report.widths.join(', ')}px`,
    `- Original breakpoints: ${report.breakpoints.length ? `${report.breakpoints.join(', ')}px` : 'none detected'}`,
    `- Parity score: **${report.summary.score}/100** · ${report.summary.high} high, ${report.summary.medium} medium, ${report.summary.low} low`,
    `- Original captured by Cloudflare Browser Run (cloud browser) on ${new Date(report.originalCapturedAt).toLocaleString()}`,
  ];
  report.results.forEach((r) => {
    out.push('', `## ${r.width}px · score ${r.score}`, '');
    out.push(`Matched ${r.stats.matched} elements · missing on migrated ${r.stats.missing} · extra on migrated ${r.stats.extra}`, '');
    out.push('| # | Severity | Status | Issue | Element | Original | Migrated |', '|---|---|---|---|---|---|---|');
    r.issues.forEach((i) => {
      const st = { ok: 'Approved', fix: 'Needs fix' }[byId[i.id]] || 'Open';
      out.push(`| ${i.n} | ${SEV[i.severity]} | ${st} | ${cell(i.title)} | ${cell(i.m?.selector || i.o?.selector)} | ${cell(i.ov)} | ${cell(i.mv)} |`);
    });
    if (!r.issues.length) out.push('| – | – | – | No differences | – | – | – |');
  });
  out.push('', '---', 'Generated by the Parity Check extension for Experience Workspace.');
  return `${out.join('\n')}\n`;
}
