/*
 * Hand-off texts: the AEM Coder prompt (parity issues from prompt.js, plus the
 * Lighthouse regressions) and a downloadable Markdown report.
 */
import { buildFixPrompt } from './prompt.js';

/** Stable key for an issue across re-runs (ids are renumbered every run). */
export const issueKey = (i) => [i.category, i.property || '', i.m?.selector || i.o?.selector || '', i.title.replace(/\d+(\.\d+)?/g, '#')].join('|');

export function statusesById(report, statuses) {
  const out = {};
  report.results.flatMap((r) => r.issues).forEach((i) => {
    if (statuses[issueKey(i)]) out[i.id] = statuses[issueKey(i)];
  });
  return out;
}

function psiSection(psi, level = '##') {
  if (!psi) return [];
  const out = ['', `${level} Lighthouse regressions (Google PageSpeed Insights, ${psi.strategy})`, ''];
  out.push(psi.categories.map((c) => `${c.title} ${c.o ?? '–'} → ${c.m ?? '–'}`).join(' · '));
  if (!psi.regressions.length) {
    out.push('', 'No Lighthouse check passes on the original and fails on the migrated page.');
  } else {
    out.push('', 'These checks pass on the original page and fail on the migrated page:');
    psi.regressions.forEach((r) => {
      const nodes = r.nodes.slice(0, 3).map((n) => `\`${n.selector}\``).join(', ');
      out.push(`- [${r.categoryTitle}] ${r.title}${r.display ? ` (${r.display})` : ''}${nodes ? ` — elements: ${nodes}` : ''}`);
    });
  }
  const worse = psi.metrics.filter((m) => m.worse);
  if (worse.length) {
    out.push('', 'Slower than the original:');
    worse.forEach((m) => out.push(`- ${m.title}: original ${m.o}, migrated ${m.m}`));
  }
  return out;
}

export function coderPrompt(report, statuses, psi) {
  let text = buildFixPrompt(report, statusesById(report, statuses));
  if (psi) {
    text = `${text.trimEnd()}\n${psiSection(psi).join('\n')}\n`;
    if (psi.regressions.length) text += '\nFix the Lighthouse regressions in the block code or content as well, without changing how the page looks.\n';
  }
  return text;
}

const SEV = { high: 'High', medium: 'Medium', low: 'Low' };
const cell = (v) => String(v ?? '–').replace(/\|/g, '\\|').replace(/\s+/g, ' ');

export function markdownReport(report, statuses, psi) {
  const r = report.results[0];
  const byId = statusesById(report, statuses);
  const out = [
    `# Parity report: ${report.title || report.migrated}`,
    '',
    `- Original page: ${report.original}`,
    `- Migrated page: ${report.migrated}`,
    `- Compared at: ${r.width}px viewport, ${new Date(report.created).toLocaleString()}`,
    `- Original breakpoints: ${report.breakpoints.length ? `${report.breakpoints.join(', ')}px` : 'none detected'}`,
    `- Parity score: **${report.summary.score}/100** · ${report.summary.high} high, ${report.summary.medium} medium, ${report.summary.low} low`,
    `- Elements matched: ${r.stats.matched} · missing on migrated: ${r.stats.missing} · extra on migrated: ${r.stats.extra}`,
    '',
    '## Visual parity issues',
    '',
    '| # | Severity | Status | Issue | Element | Original | Migrated |',
    '|---|---|---|---|---|---|---|',
  ];
  r.issues.forEach((i) => {
    const st = { ok: 'Approved', fix: 'Needs fix' }[byId[i.id]] || 'Open';
    out.push(`| ${i.n} | ${SEV[i.severity]} | ${st} | ${cell(i.title)} | ${cell(i.m?.selector || i.o?.selector)} | ${cell(i.ov)} | ${cell(i.mv)} |`);
  });
  if (!r.issues.length) out.push('| – | – | – | No differences found | – | – | – |');
  out.push(...psiSection(psi));
  out.push('', '---', 'Generated by the Parity Check extension. Lighthouse data from Google PageSpeed Insights.');
  return `${out.join('\n')}\n`;
}
